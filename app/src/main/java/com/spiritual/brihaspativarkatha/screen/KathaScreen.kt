@OptIn(ExperimentalMaterial3Api::class)
@Composable
fun KathaScreen(onBack: () -> Unit = {}) {
    TrackScreenKath("KathScreen")
    LaunchedEffect(Unit) {
        AnalyticsHelper.logEvent(
            AnalyticsEvents.KATHA_OPEN,
            mapOf("screen" to "katha_screen")
        )
    }
    val context = LocalContext.current
    val activity = context as? Activity
    val scrollState = rememberScrollState()
    val screenStartTimeMs = remember { System.currentTimeMillis() }
    val coroutineScope = rememberCoroutineScope()
    val kathaText = remember { brihaspativarKatha }

    var isScrolling by remember { mutableStateOf(false) }
    var isPlayingAudio by remember { mutableStateOf(false) }
    var currentPosition by remember { mutableIntStateOf(0) }
    var duration by remember { mutableIntStateOf(0) }

    DisposableEffect(screenStartTimeMs) {
        onDispose {
            val timeSpentMs = (System.currentTimeMillis() - screenStartTimeMs).coerceAtLeast(0L)
            val timeSpentSeconds = timeSpentMs / 1000

            AnalyticsHelper.logEvent(
                AnalyticsEvents.KATHA_TIME_SPENT,
                mapOf(
                    "screen" to "katha_screen",
                    "time_spent_sec" to timeSpentSeconds.toString(),
                    "time_spent_ms" to timeSpentMs.toString()
                )
            )
        }
    }


    // 🔒 Keep screen ON while reading
    DisposableEffect(Unit) {
        activity?.window?.addFlags(WindowManager.LayoutParams.FLAG_KEEP_SCREEN_ON)
        onDispose {
            activity?.window?.clearFlags(WindowManager.LayoutParams.FLAG_KEEP_SCREEN_ON)
        }
    }

    // 🔄 Auto Scroll Effect
    LaunchedEffect(isPlayingAudio) {

        while (isPlayingAudio) {

            if (scrollState.value < scrollState.maxValue) {
                scrollState.scrollBy(0.8f)
            }

            delay(50.milliseconds)
        }
    }

    Scaffold(
        topBar = {
            CenterAlignedTopAppBar(
                title = {
                    Text(
                        "बृहस्पतिवार व्रत कथा",
                        style = TextStyle(
                            color = Color.White,
                            fontWeight = FontWeight.Bold,
                            fontSize = 22.sp
                        )
                    )
                },
                colors = TopAppBarDefaults.topAppBarColors(
                    containerColor = Color(0xFFDAA520)
                ),
                navigationIcon = {
                    IconButton(onClick = onBack) {
                        Icon(
                            Icons.Default.ArrowBack,
                            contentDescription = null,
                            tint = Color.White
                        )
                    }
                }
            )
        },

        // 👇 ADD THIS
        bottomBar = {
            KathaAudioPlayer(
                onPlay = { isPlayingAudio = true },
                onPause = { isPlayingAudio = false }
            )
        }
    ) { padding ->
        Box(
            modifier = Modifier
                .fillMaxSize()
                .background(
                    Brush.verticalGradient(
                        listOf(
                            Color(0xFFFFF8E1),
                            Color(0xFFFFECB3),
                            Color(0xFFFFF3C2)
                        )
                    )
                )
                .padding(padding)
        ) {
            Column(
                modifier = Modifier
                    .fillMaxSize()
                    .verticalScroll(scrollState)
                    .padding(
                        start = 20.dp,
                        end = 20.dp,
                        top = 12.dp,      // 👈 add karo
                        bottom = 110.dp
                    )
            ) {
                Text(
                    text = kathaText,

                    style = MaterialTheme.typography.bodyLarge.copy(
                        fontWeight = FontWeight.Medium
                    ),

                    color = Color(0xFF4E342E),

                    fontSize = 24.sp,

                    lineHeight = 38.sp,

                    textAlign = TextAlign.Start,

                    fontFamily = FontFamily.Serif,

                    letterSpacing = 0.3.sp
                )

                Spacer(modifier = Modifier.height(20.dp))
            }
        }
    }
}

